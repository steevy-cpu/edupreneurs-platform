"""Local-only helper for the disposable Supabase stack.

    uv run python scripts/local_stack.py keys       # create the Auth signing key if missing
    uv run python scripts/local_stack.py env        # write .env from the RUNNING local stack
    uv run python scripts/local_stack.py provision  # (re)create the API's database login role

SAFETY: every command refuses to act on anything that is not on this machine
(127.0.0.1 / localhost). It never links to, reads from, or writes to a hosted
Supabase project.

No secret is hard-coded here. The API login password is generated randomly on
first run and kept in the git-ignored ``.env``. Keys of the local stack are read
from ``supabase status`` at run time.
"""

from __future__ import annotations

import asyncio
import json
import os
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import NoReturn
from urllib.parse import urlsplit

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".env"
SIGNING_KEYS = ROOT / "supabase" / "signing_keys.json"
SUPABASE_BIN = ROOT / "node_modules" / ".bin" / "supabase"
LOCAL_HOSTS = {"127.0.0.1", "localhost", "::1"}
API_LOGIN_ROLE = "edu_api_login"


def _fail(message: str) -> NoReturn:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def _supabase(*args: str, cwd: Path = ROOT) -> str:
    if not SUPABASE_BIN.exists():
        _fail("Supabase CLI not installed. Run `npm ci` (or `make install`) first.")
    completed = subprocess.run(
        [str(SUPABASE_BIN), *args], cwd=cwd, capture_output=True, text=True, check=False
    )
    if completed.returncode != 0:
        _fail(f"`supabase {' '.join(args)}` failed:\n{completed.stderr.strip()[:2000]}")
    return completed.stdout


def _require_local(url: str, what: str) -> None:
    host = urlsplit(url).hostname
    if host not in LOCAL_HOSTS:
        _fail(f"{what} points at '{host}', which is not this machine. Refusing to continue.")


def read_env_file() -> dict[str, str]:
    # Use the same dotenv parser as FastAPI's pydantic-settings source.
    return {k: v for k, v in dotenv_values(ENV_FILE).items() if v is not None}


def stack_status() -> dict[str, str]:
    raw = _supabase("status", "-o", "json")
    try:
        status = json.loads(raw[raw.index("{") : raw.rindex("}") + 1])
    except ValueError:
        _fail("Could not read `supabase status`. Is the local stack running? (`make start`)")
    _require_local(status["API_URL"], "Supabase API URL")
    _require_local(status["DB_URL"], "Database URL")
    return {str(k): str(v) for k, v in status.items()}


def cmd_keys() -> None:
    """Generate the ES256 key local Auth signs access tokens with (once)."""
    if SIGNING_KEYS.exists():
        print(f"signing key already present: {SIGNING_KEYS.relative_to(ROOT)}")
        return
    # Generated from an empty directory: inside the project the CLI would try to
    # read the (not yet existing) key file named in config.toml and stop.
    with tempfile.TemporaryDirectory() as tmp:
        raw = _supabase("gen", "signing-key", "--algorithm", "ES256", cwd=Path(tmp))
    key = json.loads(raw[raw.index("{") : raw.rindex("}") + 1])
    if key.get("kty") != "EC" or "d" not in key:
        _fail("Unexpected output from `supabase gen signing-key`.")
    fd = os.open(SIGNING_KEYS, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        json.dump([key], handle)
    print(f"created {SIGNING_KEYS.relative_to(ROOT)} (git-ignored, local only)")


def cmd_env() -> None:
    """Write .env for the API and the test-suite from the running local stack."""
    from disposable import verify

    verify()
    status = stack_status()
    existing = read_env_file()
    password = existing.get("LOCAL_API_DB_PASSWORD") or secrets.token_urlsafe(32)
    db = urlsplit(status["DB_URL"])
    api_url = status["API_URL"].rstrip("/")
    lines = [
        "# Generated by scripts/local_stack.py for the LOCAL stack only. Do not commit.",
        "",
        "# --- read by the API (services/api) ---",
        "EDU_ENVIRONMENT=local",
        f"EDU_DATABASE_URL=postgresql+asyncpg://{API_LOGIN_ROLE}:{password}@{db.hostname}:{db.port}{db.path}",
        f"EDU_AUTH_ISSUER={api_url}/auth/v1",
        f"EDU_AUTH_JWKS_URL={api_url}/auth/v1/.well-known/jwks.json",
        "EDU_AUTH_AUDIENCE=authenticated",
        'EDU_AUTH_ALGORITHMS=["ES256"]',
        "",
        "# --- read ONLY by local tooling and tests, never by the API process ---",
        f"LOCAL_API_DB_PASSWORD={password}",
        f"LOCAL_SUPABASE_URL={api_url}",
        f"LOCAL_SUPABASE_PUBLISHABLE_KEY={status['PUBLISHABLE_KEY']}",
        f"LOCAL_SUPABASE_SECRET_KEY={status['SECRET_KEY']}",
        # Legacy JWT-format project keys: used by one test that proves they are
        # NOT accepted as user access tokens.
        f"LOCAL_SUPABASE_ANON_JWT={status.get('ANON_KEY', '')}",
        f"LOCAL_SUPABASE_SERVICE_ROLE_JWT={status.get('SERVICE_ROLE_KEY', '')}",
        f"LOCAL_ADMIN_DATABASE_URL={status['DB_URL']}",
        "",
    ]
    fd = os.open(ENV_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    os.chmod(ENV_FILE, 0o600)
    print(f"wrote {ENV_FILE.relative_to(ROOT)} (git-ignored)")


async def _provision(admin_url: str, password: str) -> None:
    import asyncpg

    conn = await asyncpg.connect(admin_url, timeout=10)
    try:
        if not await conn.fetchval("SELECT 1 FROM pg_roles WHERE rolname = 'edu_api'"):
            _fail("Role edu_api does not exist. Run `make db-reset` to apply the migrations.")
        exists = await conn.fetchval("SELECT 1 FROM pg_roles WHERE rolname = $1", API_LOGIN_ROLE)
        verb = "ALTER" if exists else "CREATE"
        # A role password cannot be a bound parameter in DDL, so PostgreSQL's own
        # format(%L) quotes it as a literal. The value never appears in this file.
        statement = await conn.fetchval(
            "SELECT format('%s ROLE %I LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE "
            "NOREPLICATION NOBYPASSRLS INHERIT CONNECTION LIMIT 40 PASSWORD %L', "
            "$1::text, $2::text, $3::text)",
            verb,
            API_LOGIN_ROLE,
            password,
        )
        await conn.execute(statement)
        await conn.execute(f'GRANT edu_api TO "{API_LOGIN_ROLE}"')
        other_roles = await conn.fetch(
            "SELECT g.rolname FROM pg_auth_members m JOIN pg_roles g ON g.oid = m.roleid "
            "JOIN pg_roles u ON u.oid = m.member WHERE u.rolname = $1 AND g.rolname <> 'edu_api'",
            API_LOGIN_ROLE,
        )
        if other_roles:
            _fail(f"{API_LOGIN_ROLE} unexpectedly belongs to other roles: {other_roles}")
    finally:
        await conn.close()


def cmd_provision() -> None:
    """Create the login role the API connects as (member of edu_api only)."""
    from disposable import verify

    env = read_env_file()
    verify(env=env)
    admin_url = env.get("LOCAL_ADMIN_DATABASE_URL")
    password = env.get("LOCAL_API_DB_PASSWORD")
    if not admin_url or not password:
        _fail("Run `uv run python scripts/local_stack.py env` first.")
    _require_local(admin_url, "LOCAL_ADMIN_DATABASE_URL")
    asyncio.run(_provision(admin_url, password))
    print(f"database login role '{API_LOGIN_ROLE}' is ready (member of edu_api, no BYPASSRLS)")


COMMANDS = {"keys": cmd_keys, "env": cmd_env, "provision": cmd_provision}

if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in COMMANDS:
        _fail(f"usage: local_stack.py {{{'|'.join(COMMANDS)}}}")
    COMMANDS[sys.argv[1]]()
