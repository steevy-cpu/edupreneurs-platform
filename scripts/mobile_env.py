"""Write apps/student-native/.env.local for the LOCAL stack.

    uv run python scripts/mobile_env.py ios-sim       # iOS Simulator (shares the Mac's network)
    uv run python scripts/mobile_env.py android-emu   # Android emulator (10.0.2.2 = the Mac)
    uv run python scripts/mobile_env.py lan           # a real phone on the same Wi-Fi

The values are not secrets: two local URLs and the local project's publishable
key. The file is git-ignored anyway, because it is machine-specific.
"""

from __future__ import annotations

import socket
import sys
from pathlib import Path
from urllib.parse import urlsplit

from local_stack import LOCAL_HOSTS, ROOT, read_env_file

TARGETS = ("ios-sim", "android-emu", "lan")
OUTPUT = ROOT / "apps" / "student-native" / ".env.local"
API_PORT = 8000


def lan_address() -> str:
    """This machine's address on the local network (no packet is sent)."""
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("192.0.2.1", 9))  # TEST-NET-1: only selects the outgoing interface
        return str(probe.getsockname()[0])
    except OSError:
        raise SystemExit("error: no local network address found. Connect to Wi-Fi first.") from None
    finally:
        probe.close()


def main(target: str) -> None:
    env = read_env_file()
    supabase_url = env.get("LOCAL_SUPABASE_URL")
    key = env.get("LOCAL_SUPABASE_PUBLISHABLE_KEY")
    if not supabase_url or not key:
        raise SystemExit("error: run `make db-reset` first (the root .env is missing).")
    parts = urlsplit(supabase_url)
    if parts.hostname not in LOCAL_HOSTS:
        raise SystemExit("error: LOCAL_SUPABASE_URL is not this machine. Refusing to continue.")
    host = {"ios-sim": "127.0.0.1", "android-emu": "10.0.2.2"}.get(target) or lan_address()
    lines = [
        f"# Generated by scripts/mobile_env.py ({target}). Local development only. Not secret.",
        f"EXPO_PUBLIC_API_URL=http://{host}:{API_PORT}",
        f"EXPO_PUBLIC_SUPABASE_URL=http://{host}:{parts.port}",
        f"EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY={key}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} for {target} (API at http://{host}:{API_PORT})")


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in TARGETS:
        raise SystemExit(f"usage: mobile_env.py {{{'|'.join(TARGETS)}}}")
    main(sys.argv[1])
    assert Path(OUTPUT).exists()
